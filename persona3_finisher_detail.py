@lru_cache(maxsize=16)
def _backdrop(name, bg, w, h):
    """Cache the static screen-print field; gestures draw over a fresh copy."""
    c=DotCanvas(w,h)
    plate=_PLATES[name]
    W,H=c.w,c.h
    px=.29 if plate.facing < 0 else .73
    rx,ry=W*.42,H*.65
    cx,cy=W*px,H*.49
    for y in range(H):
        for x in range(W):
            r=((x-cx)/rx)**2+((y-cy)/ry)**2
            lean=x+y*.9 if plate.facing<0 else x-y*.9
            if .86<r<.91 and (x+y)%7<5:
                c.put(x,y,bg.glow)
            elif r<.84 and (3*x+5*y)%17<2:
                c.put(x,y,bg.mid)
            elif (lean%91<2 and r>.4) or (r>1 and (x*3+y*7)%61<2):
                c.put(x,y,bg.shadow)
    if plate.motif in ('arc','echo','target'):
        count=5 if plate.motif=='target' else 3
        for i in range(count):
            c.ring(cx,cy,rx*(.93+.086*i),ry*(.93+.086*i),bg.mid,
                   start=-1.7+i*.28,stop=-.35+i*.28,steps=26)
        if plate.motif=='target':
            for i in range(4):
                a=i*tau/4
                c.line((cx+cos(a)*rx*.89,cy+sin(a)*ry*.89),
                       (cx+cos(a)*rx*.83,cy+sin(a)*ry*.83),bg.glow)
    elif plate.motif=='ribbon':
        # A few sweep contours pick up the direction of the hair or sleeve.
        for i in range(4):
            c.path(tuple((W*(j/19), H*(.16+.095*i + sin(j*.27+i*.35)*.10+.017*j))
                         for j in range(20)),bg.shadow if i%2 else bg.mid)
    elif plate.motif=='corner':
        for i in range(4):
            x,y=W*(.35+i*.028),H*(.05+i*.071)
            c.path(((0,y+H*.50),(x,y),(W*.89,y-H*.08)),bg.mid if i==0 else bg.shadow)
    elif plate.motif=='tilt':
        for i in range(4):
            c.line((W*.15+i*W*.06,H),(W*.88+i*W*.06,0),
                   bg.mid if i%3==0 else bg.shadow)
    else:
        for i in range(7):
            c.path(((i*W*.055,H*.93),(W*.16+i*W*.065,H*.93),
                    (W*.56+i*W*.051,H*.08)),bg.mid if i%2 else bg.shadow)
    return tuple(tuple(row) for row in c.rows)


